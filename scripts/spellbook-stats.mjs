#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name === '.git' || name === 'node_modules') continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, acc);
    else if (name.endsWith('.md')) acc.push(p);
  }
  return acc;
}

const scopes = ['skills', 'evals', 'demos'];
let files = 0;
let lines = 0;
const byScope = {};

for (const scope of scopes) {
  const dir = join(root, scope);
  let f = 0;
  let l = 0;
  for (const p of walk(dir)) {
    f++;
    l += readFileSync(p, 'utf8').split('\n').length;
  }
  byScope[scope] = { files: f, lines: l };
  files += f;
  lines += l;
}

const lenses = walk(join(root, 'skills/archon/references/lenses')).length;
const golden = readFileSync(join(root, 'evals/GOLDEN.md'), 'utf8');
const gCount = (golden.match(/^## G\d+/gm) || []).length;
const examples = readFileSync(join(root, 'skills/archon/references/worked-examples.md'), 'utf8');
const exCount = (examples.match(/^## Example /gm) || []).length;

const out = {
  generated_at: new Date().toISOString().slice(0, 10),
  markdown_files: files,
  markdown_lines: lines,
  by_scope: byScope,
  lens_packs: lenses,
  golden_prompts: gCount,
  worked_examples: exCount,
  permanent_chamber_seats: 4,
};

if (process.argv.includes('--json')) {
  console.log(JSON.stringify(out, null, 2));
} else {
  console.log(`Spellbook size (${out.generated_at})`);
  console.log(
    `- Markdown files: ${files} (skills ${byScope.skills.files} · evals ${byScope.evals.files} · demos ${byScope.demos.files})`,
  );
  console.log(`- Markdown lines: ${lines}`);
  console.log(
    `- Lens packs: ${lenses} · GOLDEN prompts: ${gCount} · Worked examples: ${exCount}`,
  );
  console.log(`- Permanent chamber seats: 4 (hard cap)`);
}

const md = `# Spellbook size

Generated by \`npm run stats\` — honest inventory, not a vanity race with Grim.

| Metric | Value |
|--------|------:|
| Date | ${out.generated_at} |
| Markdown files (skills+evals+demos) | ${files} |
| Markdown lines | ${lines} |
| skills/ | ${byScope.skills.files} files · ${byScope.skills.lines} lines |
| evals/ | ${byScope.evals.files} files · ${byScope.evals.lines} lines |
| demos/ | ${byScope.demos.files} files · ${byScope.demos.lines} lines |
| Lens packs | ${lenses} |
| GOLDEN prompts | ${gCount} |
| Worked examples | ${exCount} |
| Permanent chamber seats | **4** (cap) |

Depth goal = method usefulness under pressure, not page count (\`compounds.md\`).
`;
writeFileSync(join(root, 'SPELLBOOK-SIZE.md'), md);
